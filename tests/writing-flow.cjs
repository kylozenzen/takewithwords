const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/app.html');
 await page.locator('[data-act="tour-dismiss"]').click();
 assert.equal(await page.locator('.start-choices article').count(),3);
 await page.locator('[data-act="develop-new"]').click();
 await page.locator('#developmentAnswer').fill('A small project taught me to ask better questions.');
 await page.locator('.btn[data-act="develop-next"]').click();
 await page.locator('#developmentAnswer').fill('I expected the code to be the hard part.');
 await page.reload();
 assert.equal(await page.locator('#developmentAnswer').inputValue(),'I expected the code to be the hard part.');
 await page.locator('.btn[data-act="develop-next"]').click();
 await page.locator('#developmentAnswer').fill('A creator described the problem in one sentence.');
 await page.locator('.btn[data-act="develop-next"]').click();
 await page.locator('#developmentAnswer').fill('Other builders who need to listen first.');
 await page.locator('.btn[data-act="develop-next"]').click();
 await page.locator('[data-act="develop-angle"][data-id="story"]').click();
 await page.locator('.btn[data-act="develop-write"]').click();
 assert.equal(await page.locator('#bodyInput').inputValue(),'');
 await page.locator('#bodyInput').fill('Here is the story, in my own words.');
 await page.reload();
 assert.equal(await page.locator('#bodyInput').inputValue(),'Here is the story, in my own words.');
 await page.locator('.development-notes summary').click();
 assert.match(await page.locator('.development-notes').innerText(),/A small project/);
 await page.locator('[data-view="opinions"]').click();
 assert.equal(await page.locator('[data-view="opinions"]').getAttribute('aria-current'),'page');
 await page.locator('[data-act="ref-add"]').click();
 await page.locator('#refName').fill('Alex Writer');
 await page.locator('#refHandle').fill('https://example.com/alex');
 await page.locator('#refNote').fill('Specific stories and clear lessons.');
 await page.locator('#refForm button[type="submit"]').click();
 assert.equal(await page.locator('.ref-list li').count(),1);
 await page.locator('[data-act="ref-edit"]').click();
 await page.locator('#refNote').fill('An edited note.');
 await page.locator('#refForm button[type="submit"]').click();
 await page.locator('#creatorSearch').fill('missing');
 assert.match(await page.locator('#refList').innerText(),/No matches/);
 await page.locator('#creatorSearch').fill('edited');
 assert.equal(await page.locator('.ref-list li').count(),1);
 await page.reload();
 assert.match(await page.locator('#refList').innerText(),/An edited note/);
 await page.screenshot({animations:'disabled',path:'/tmp/tww-opinions-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({animations:'disabled',path:'/tmp/tww-opinions-mobile.png'});
 await page.locator('[data-ref-remove]').click();
 assert.match(await page.locator('#refList').innerText(),/Who makes you stop scrolling/);
 await page.locator('[data-act="mobile-menu"]').click();
 await page.locator('[data-view="today"]').click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({animations:'disabled',path:'/tmp/tww-start-mobile.png'});
 await page.locator('[data-act="blank"]').click();
 assert.equal(await page.locator('#bodyInput').inputValue(),'');
 await page.locator('[data-act="go-today"]').click();
 await page.locator('[data-act="go-spark"]').first().click();
 await page.locator('[data-act="start"]').first().click();
 assert.equal(await page.locator('.prompt-strip').count(),1);
 assert.deepEqual(errors,[]);
 console.log('PASS: guided answers, reload persistence, private source, creator CRUD/search, all three starts, mobile overflow, no runtime errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
